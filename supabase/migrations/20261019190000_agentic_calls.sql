-- Agentic / Claude advisory layer — per-call token accounting.
-- Records every Anthropic API call with model, tokens, and cost for
-- monthly cap enforcement and spend visibility.
--
-- MIGRATION ONLY — do not apply manually. Reviewed in PR.

SET search_path = public;

CREATE TABLE IF NOT EXISTS agentic_calls (
  id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  created_at    timestamptz NOT NULL DEFAULT now(),
  component     text        NOT NULL,  -- news_filter | regime_advisor | daily_review | research | pr_reviewer
  model         text        NOT NULL,  -- e.g. claude-haiku-5-5
  input_tokens  integer     NOT NULL DEFAULT 0,
  output_tokens integer     NOT NULL DEFAULT 0,
  cache_read_tokens  integer NOT NULL DEFAULT 0,
  cache_write_tokens integer NOT NULL DEFAULT 0,
  cost_usd      numeric(10,6) NOT NULL DEFAULT 0,
  duration_ms   integer,
  batch_id      text,                  -- non-null for Message Batches API calls
  metadata      jsonb,                 -- component-specific payload (regime JSON, report id, etc.)
  error         text                   -- non-null when the call failed
);

COMMENT ON TABLE agentic_calls IS 'Per-call token accounting for the Anthropic Claude advisory layer.';

CREATE INDEX IF NOT EXISTS idx_agentic_calls_created_at ON agentic_calls (created_at);
CREATE INDEX IF NOT EXISTS idx_agentic_calls_component  ON agentic_calls (component);

-- Monthly spend view for cap enforcement.
CREATE OR REPLACE VIEW agentic_monthly_spend AS
  SELECT
    date_trunc('month', created_at) AS month,
    component,
    count(*)                        AS call_count,
    sum(input_tokens)               AS total_input_tokens,
    sum(output_tokens)              AS total_output_tokens,
    sum(cost_usd)                   AS total_cost_usd
  FROM agentic_calls
  WHERE error IS NULL
  GROUP BY 1, 2;

-- Agentic reports (daily risk review, research cards).
CREATE TABLE IF NOT EXISTS agentic_reports (
  id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  created_at    timestamptz NOT NULL DEFAULT now(),
  report_type   text        NOT NULL,  -- daily_risk_review | research_card
  title         text,
  markdown      text        NOT NULL,
  metadata      jsonb,
  call_id       bigint REFERENCES agentic_calls(id)
);

COMMENT ON TABLE agentic_reports IS 'Reports generated by the Claude advisory layer (risk reviews, research cards).';

CREATE INDEX IF NOT EXISTS idx_agentic_reports_type ON agentic_reports (report_type, created_at DESC);

-- RLS: service_role only (the runtime writes via service key).
ALTER TABLE agentic_calls  ENABLE ROW LEVEL SECURITY;
ALTER TABLE agentic_reports ENABLE ROW LEVEL SECURITY;

CREATE POLICY "service_role_agentic_calls" ON agentic_calls
  FOR ALL TO service_role USING (true) WITH CHECK (true);
CREATE POLICY "service_role_agentic_reports" ON agentic_reports
  FOR ALL TO service_role USING (true) WITH CHECK (true);

-- Authenticated users can read (desk dashboard).
CREATE POLICY "authenticated_read_agentic_calls" ON agentic_calls
  FOR SELECT TO authenticated USING (true);
CREATE POLICY "authenticated_read_agentic_reports" ON agentic_reports
  FOR SELECT TO authenticated USING (true);
